#!/usr/bin/env python3
"""Native primitives, Do 4: summarise paired interleaved runs (bench/np/run_bench.sh) into DIR/summary.md and
DIR/summary.json.

  summarize_bench.py DIR [--base TAG] [--new TAG]   # writes DIR/summary.md, summary.json
  summarize_bench.py DIR ... --check                 # recomputes and compares byte for byte (exit 1 on a difference)

TAGs are BUILD-SHIM (default on-none = S0's configuration, on-on = native heaps).  Per workload and arm, over runs:
user and wall seconds (sum over the workload's files in that run), peak RSS (largest file's maximum resident set in
that run); paired ratios new/base run by run (both arms of batch r ran back to back under one lock); answers (every
run's check line: exit 0, stdout byte-identical to S0's recorded base stdout for the same file, no failed test);
profiler rows (self seconds summed over the workload's files, median over runs) before and after; native heap
counters (*.np-heaps.json) of the new arm.
"""
import argparse
import glob
import json
import os
import re
import statistics
import sys

WORKLOADS = ["w1-examples", "w2-wmtm", "w3-benchgen"]
ROWS = ["advance-frontier-waiter-heap", "spawn-frontier-goal-heap", "spawn-frontier-heap",
        "commit-proof-candidate-heap", "schedule-goal-heap", "frontier-remaining-score", "proof-output-key-by-id",
        "goal-merged-proof-ids", "store-proof-candidate", "externalize-compiled-addition", "<outside-equations>"]
HEAP_CALLERS = ["search-agenda-heap", "schedule-goal-row", "schedule-aggregate-heap", "heap-take-best", "heap-take-best-pop", "heap-prune-to-size", "forward-pop-agenda"]


def med(xs):
    return statistics.median(xs) if xs else float("nan")


def rng(xs, fmt="%.3f"):
    return (fmt + " (" + fmt + "-" + fmt + ")") % (med(xs), min(xs), max(xs)) if xs else "-"


def load(d, tag):
    runs = {}
    for w in WORKLOADS:
        for t in sorted(glob.glob(os.path.join(d, w, "*.%s.r*.time" % tag))):
            m = re.match(r"(.*)\.%s\.r(\d+)\.time$" % re.escape(tag), os.path.basename(t))
            name, r = m.group(1), int(m.group(2))
            base = t[:-len(".time")]
            wall, user, sys_, rss = open(t).read().split()[-4:]
            check = open(base + ".check").read().strip()
            prof = {}
            if os.path.exists(base + ".fnprof.json"):
                fp = json.load(open(base + ".fnprof.json"))
                prof["_total"] = fp["total_ns"]
                for f in fp["functions"]:
                    prof[f["head"]] = f["self_ns"]
            heaps = json.load(open(base + ".np-heaps.json")) if os.path.exists(base + ".np-heaps.json") else None
            runs.setdefault((w, r), []).append({"name": name, "wall": float(wall), "user": float(user),
                                                "rss_kb": int(rss), "check": check, "prof": prof, "heaps": heaps})
    return runs


def ok(check):
    return (check.startswith("exit=0 ") and "answers_vs_s0_base=same" in check and "failed_tests=0" in check
            and "route=FAILED" not in check and ("heaps=" not in check or "route=ok" in check))


def build(d, base_tag, new_tag):
    A, B = load(d, base_tag), load(d, new_tag)
    lines = ["# Paired end-to-end runs: %s (base) vs %s (new)" % (base_tag, new_tag), "",
             "Generated by bench/np/summarize_bench.py from %s; per workload, sums over its files per run; ratios are "
             "new/base of the same batch (back to back, one lock); median (min-max) over runs." % d, ""]
    out = {"base": base_tag, "new": new_tag, "workloads": {}}
    lines += ["| workload | runs | file-runs (base+new) | answers same as S0, exit 0, no failed test | base user s | new user s "
              "| paired user ratio new/base | paired wall ratio | base peak RSS MB | new peak RSS MB |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    rows_tables = []
    for w in WORKLOADS:
        rs = sorted(r for (ww, r) in A if ww == w and (w, r) in B)
        if not rs:
            continue
        fa = [x for r in rs for x in A[(w, r)]]
        fb = [x for r in rs for x in B[(w, r)]]
        good = sum(ok(x["check"]) for x in fa + fb)
        ua = [sum(x["user"] for x in A[(w, r)]) for r in rs]
        ub = [sum(x["user"] for x in B[(w, r)]) for r in rs]
        wa = [sum(x["wall"] for x in A[(w, r)]) for r in rs]
        wb = [sum(x["wall"] for x in B[(w, r)]) for r in rs]
        ma = [max(x["rss_kb"] for x in A[(w, r)]) / 1024 for r in rs]
        mb = [max(x["rss_kb"] for x in B[(w, r)]) / 1024 for r in rs]
        ru = [b / a for a, b in zip(ua, ub)]
        rw = [b / a for a, b in zip(wa, wb)]
        lines.append("| %s | %d | %d | %d of %d | %s | %s | %s | %s | %s | %s |" % (
            w, len(rs), len(fa) + len(fb), good, len(fa) + len(fb), rng(ua, "%.1f"), rng(ub, "%.1f"), rng(ru),
            rng(rw), rng(ma, "%.0f"), rng(mb, "%.0f")))
        wo = {"runs": rs, "file_runs": len(fa) + len(fb), "answers_ok": good, "user_base": ua, "user_new": ub,
              "wall_base": wa, "wall_new": wb, "rss_mb_base": ma, "rss_mb_new": mb, "ratio_user": ru,
              "ratio_wall": rw}
        # profiler rows
        if fa and fa[0]["prof"]:
            tot_a = [sum(x["prof"].get("_total", 0) for x in A[(w, r)]) / 1e9 for r in rs]
            tot_b = [sum(x["prof"].get("_total", 0) for x in B[(w, r)]) / 1e9 for r in rs]
            t = ["", "#### %s: profiler rows, self seconds (sum over files; median over runs, min-max)" % w, "",
                 "| row | base | new | new/base (median of paired ratios) |", "|---|---|---|---|",
                 "| profiled total | %s | %s | %.3f |" % (rng(tot_a, "%.2f"), rng(tot_b, "%.2f"),
                                                        med([b / a for a, b in zip(tot_a, tot_b)]))]
            wo["rows"] = {}
            for row in ROWS + HEAP_CALLERS:
                sa = [sum(x["prof"].get(row, 0) for x in A[(w, r)]) / 1e9 for r in rs]
                sb = [sum(x["prof"].get(row, 0) for x in B[(w, r)]) / 1e9 for r in rs]
                if max(sa + sb) < 0.05:
                    continue
                pr = [b / a for a, b in zip(sa, sb) if a > 0]
                t.append("| %s | %s | %s | %s |" % (row, rng(sa, "%.2f"), rng(sb, "%.2f"),
                                                     "%.3f" % med(pr) if pr else "-"))
                wo["rows"][row] = {"base": sa, "new": sb}
            rows_tables += t
        hs = [x["heaps"] for x in fb if x["heaps"]]
        if hs:
            tot = {k: sum(op[k] for h in hs for op in h["ops"]) for k in ("calls", "native", "declined")}
            wo["heaps_new"] = tot
            rows_tables += ["", "%s, new arm: %d heap calls over its file-runs, %d answered natively, %d declined to "
                            "SWI-Prolog." % (w, tot["calls"], tot["native"], tot["declined"])]
        out["workloads"][w] = wo
    lines += rows_tables
    return "\n".join(lines) + "\n", json.dumps(out, indent=1, sort_keys=True) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dir")
    ap.add_argument("--base", default="on-none")
    ap.add_argument("--new", default="on-on")
    ap.add_argument("--name", default="summary")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    md, js = build(a.dir, a.base, a.new)
    pmd, pjs = os.path.join(a.dir, a.name + ".md"), os.path.join(a.dir, a.name + ".json")
    if a.check:
        same = open(pmd).read() == md and open(pjs).read() == js
        print("identical" if same else "DIFFERS")
        sys.exit(0 if same else 1)
    open(pmd, "w").write(md)
    open(pjs, "w").write(js)
    print(md)


if __name__ == "__main__":
    main()
