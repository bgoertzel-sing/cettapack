#!/usr/bin/env python3
"""Native primitives: the per-run check lines (sanity gate) of a runs directory as one table, plus the heap counters.

  summarize_checks.py DIR            # writes DIR/checks.md
  summarize_checks.py DIR --check    # recomputes and compares byte for byte (exit 1 on a difference)

A file-run passes when its check line says exit=0, answers_vs_s0_base=same, failed_tests=0 and, with a shim,
route=ok (heap_pop answered natively / compared equal in check mode / not answered with the switch off).
"""
import glob
import json
import os
import sys


def build(d):
    lines = ["# Check lines of %s" % d, "", "Generated by bench/np/summarize_checks.py.", "",
             "| workload | file-run | exit | answers vs S0 base | failed tests | heap counters (sum over ops) | route | pass |",
             "|---|---|---|---|---|---|---|---|"]
    n = good = 0
    heaps = {}
    for f in sorted(glob.glob(os.path.join(d, "*", "*.check"))):
        w = os.path.basename(os.path.dirname(f))
        tag = os.path.basename(f)[:-len(".check")]
        kv = dict(x.split("=", 1) for x in open(f).read().split())
        ok = (kv.get("exit") == "0" and kv.get("answers_vs_s0_base") == "same" and kv.get("failed_tests") == "0"
              and kv.get("route", "ok") == "ok")
        n += 1
        good += ok
        lines.append("| %s | %s | %s | %s | %s | %s | %s | %s |" % (
            w, tag, kv.get("exit"), kv.get("answers_vs_s0_base"), kv.get("failed_tests"), kv.get("heaps", "-"),
            kv.get("route", "-"), "yes" if ok else "NO"))
        hj = f[:-len(".check")] + ".np-heaps.json"
        if os.path.exists(hj):
            for o in json.load(open(hj))["ops"]:
                for k in ("calls", "native", "declined", "checked", "mismatched"):
                    heaps[(o["name"], k)] = heaps.get((o["name"], k), 0) + o[k]
    lines += ["", "**%d of %d file-runs pass.**" % (good, n)]
    if heaps:
        names = sorted({k[0] for k in heaps}, key=lambda x: (x != "heap_pop", x))
        lines += ["", "Heap counters over all file-runs (calls reaching CeTTa's Prolog bridge; heap_pop is the one 0010 "
                  "answers, the others count calls CeTTa's own native heap declined):", "",
                  "| function | calls | native | declined (ran in SWI) | checked | mismatched |", "|---|---|---|---|---|---|"]
        for nm in names:
            lines.append("| %s | %d | %d | %d | %d | %d |" % ((nm,) + tuple(
                heaps[(nm, k)] for k in ("calls", "native", "declined", "checked", "mismatched"))))
    return "\n".join(lines) + "\n"


def main():
    d = sys.argv[1]
    md = build(d)
    p = os.path.join(d, "checks.md")
    if "--check" in sys.argv:
        same = open(p).read() == md
        print("identical" if same else "DIFFERS")
        sys.exit(0 if same else 1)
    open(p, "w").write(md)
    print(md.splitlines()[-1] if md else "")


if __name__ == "__main__":
    main()
