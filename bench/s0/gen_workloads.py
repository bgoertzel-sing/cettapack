#!/usr/bin/env python3
"""S0 workload generator (t-2026-11-24-cettapack-s0-profile): synthetic PeTTaChainer programs.

  w2-wmtm      wmtm-style reasoning run: the shape of wmtm's shadow KB (an Inheritance taxonomy,
               instance facts, per-note Implication rules over instances with CTV truth values,
               PeTTaChainer's native Inheritance chaining) and its goals (an instance against a class
               2-3 hops up, plus negative controls).  At PeTTaChainer b0e24f9 instances are written
               with Inheritance (its examples do; wmtm's later Member form is 33cca343-era).
               Vocabulary: the words of wmtm's synthetic fixture (tests/fixtures/synthetic/
               wmtm_state.json, sha256 checked); no note data.
  w3-benchgen  larger KB: PeTTaChainer's own benchmark generator (benchmarks/benchgen_metta.metta at
               b0e24f9) ported statement for statement to Python so the truth values come from a
               seeded RNG (benchgen draws them with random-float, which is not seedable in CeTTa);
               the same base facts, main rules (premises joined by seq2expr -> And), meta and
               tracking statements, backward/forward noise chains, and BenchTarget queries.

Every output starts with a header naming the generator, its arguments and seed.
"""
import argparse
import hashlib
import json
import random
import re
import sys

WMTM_FIXTURE_SHA256 = None  # recorded in the header; checked when --fixture-sha256 is given


def header(kind, args):
    shown = {k: v for k, v in vars(args).items() if k not in ("out", "fixture")}
    return (";; generated by bench/s0/gen_workloads.py %s %s\n"
            ";; synthetic data only (cettapack S0); do not edit, regenerate\n"
            "!(import! &self ../petta_chainer)\n\n" % (kind, json.dumps(shown, sort_keys=True)))


def conf(rng):
    # benchgen's BenchGlobalConf: (random-float 0.45 0.98); rounded so the file is stable text
    return round(rng.uniform(0.45, 0.98), 4)


def gen_wmtm(args):
    raw = open(args.fixture, "rb").read()
    digest = hashlib.sha256(raw).hexdigest()
    if args.fixture_sha256 and digest != args.fixture_sha256:
        sys.exit("fixture sha256 %s != %s" % (digest, args.fixture_sha256))
    state = json.loads(raw)
    words = set()
    for item in state["store"]["items"].values():
        for w in re.findall(r"[A-Za-z]{4,}", item.get("content", "")):
            words.add(w.lower())
    vocab = sorted(words)
    rng = random.Random(args.seed)
    rng.shuffle(vocab)
    if len(vocab) < args.classes + args.entities:
        sys.exit("fixture vocabulary too small: %d" % len(vocab))
    classes = ["c_" + w for w in vocab[:args.classes]]
    entities = ["e_" + w for w in vocab[args.classes:args.classes + args.entities]]
    kb = args.kb
    out = [header("w2-wmtm", args), ";; fixture sha256 %s, %d words\n" % (digest, len(vocab))]
    parent = {}
    roots = max(1, args.classes // 8)
    for i, c in enumerate(classes):
        if i < roots:
            continue
        p = classes[rng.randrange(0, i)]
        parent[c] = p
        out.append("!(compileadd %s (: inh_%s (Inheritance %s %s) (STV 1.0 0.9)))\n" % (kb, c[2:], c, p))
    leaves = [c for c in classes if c not in parent.values()] or classes
    member = {}
    for i, e in enumerate(entities):
        c = rng.choice(leaves)
        member[e] = c
        out.append("!(compileadd %s (: mem_%s (Inheritance %s %s) (STV %s 0.9)))\n" % (kb, e[2:], e, c, conf(rng)))
    for i in range(args.rules):
        # upward only (b before a in the class order, as every taxonomy parent is): the rule graph stays a DAG
        ia, ib = sorted(rng.sample(range(len(classes)), 2), reverse=True)
        a, b = classes[ia], classes[ib]
        out.append("!(compileadd %s (: note%d_impl (Implication (Inheritance $x %s) (Inheritance $x %s)) (CTV (STV %s 0.9) (STV 0.0 1.0))))\n"
                   % (kb, i, a, b, conf(rng)))

    def ancestors(c):
        seen = []
        while c in parent:
            c = parent[c]
            seen.append(c)
        return seen
    goals = []
    ents = list(entities)
    rng.shuffle(ents)
    for e in ents:
        anc = ancestors(member[e])
        if len(anc) >= 2:
            goals.append((e, anc[min(len(anc) - 1, rng.choice((1, 2)))], "pos"))
        if len([g for g in goals if g[2] == "pos"]) >= args.goals:
            break
    for e in ents[:args.negatives]:
        anc = set(ancestors(member[e])) | {member[e]}
        cands = [c for c in classes if c not in anc]
        goals.append((e, rng.choice(cands), "neg"))
    out.append("\n")
    for e, c, kind in goals:
        out.append(";; goal %s\n!(collapse (query %d %s (: $prf (Inheritance %s %s) $tv)))\n" % (kind, args.steps, kb, e, c))
    return "".join(out)


def gen_benchgen(args):
    rng = random.Random(args.seed)
    b, kb = args.bench, args.kb
    out = [header("w3-benchgen", args)]
    stmts = []

    def add(stmt):
        stmts.append("!(compileadd %s %s)\n" % (kb, stmt))

    def meta(prf, typ):
        add("(: %s %s (STV 1.0 1.0))" % (prf, typ))

    def tracked(tag, stmt):
        add(stmt)
        add("(: (bench-pln-atom %s %s) (BenchPLNAtom %s %s) (STV 1.0 1.0))" % (b, tag, b, stmt))

    def premise_ref(path, level, idx):
        return "(BenchFact %s %d %d)" % (b, path, idx) if level == 0 else "(BenchNode %s %d %d %d)" % (b, path, level, idx)

    def seq2expr(items):
        return items[0] if len(items) == 1 else "(And %s)" % " ".join(items)

    D, W, P = args.depth, args.width, args.paths
    true_count = 0
    for path in range(1, P + 1):
        for idx in range(1, W ** D + 1):
            c = conf(rng)
            tracked("(base-fact %d %d)" % (path, idx),
                    "(: (bench-base-fact %s %d %d) (BenchFact %s %d %d) (STV 1.0 %s))" % (b, path, idx, b, path, idx, c))
            true_count += 1
        for level in range(1, D + 1):
            for idx in range(1, W ** (D - level) + 1):
                prem = [premise_ref(path, level - 1, (idx - 1) * W + slot) for slot in range(1, W + 1)]
                concl = "(BenchTarget %s %d)" % (b, path) if level == D else "(BenchNode %s %d %d %d)" % (b, path, level, idx)
                c = conf(rng)
                stmt = "(: (bench-main-rule %s %d %d %d) (Implication %s %s) (CTV (STV 1.0 %s) (STV 0.0 1.0)))" % (
                    b, path, level, idx, seq2expr(prem), concl, c)
                meta("(bench-main-meta %s %d %d %d)" % (b, path, level, idx), "(BenchMainRule %s %d %d %d %d)" % (b, path, level, idx, W))
                meta("(bench-main-premise-meta %s %d %d %d)" % (b, path, level, idx), "(BenchMainPremiseCount %s %d %d %d %d)" % (b, path, level, idx, W))
                meta("(bench-main-conf %s %d %d %d)" % (b, path, level, idx), "(BenchMainConf %s %d %d %d %s)" % (b, path, level, idx, c))
                tracked("(main-rule %d %d %d)" % (path, level, idx), stmt)
                true_count += 1
    noise_total = args.noise_factor * true_count
    desired_back = noise_total * args.backward_ratio // 100
    back_budget = 0 if desired_back < 1 else min(noise_total, desired_back)
    fwd_budget = noise_total - back_budget

    def cycle1(i, m):
        return (i - 1) % m + 1
    noise_idx, remaining = 1, back_budget
    while remaining > 0:
        span = min(remaining, max(1, args.backward_chain_len))
        path = cycle1(noise_idx, P)
        head_prem = "(NoiseBlocker %s %d)" % (b, noise_idx) if span == 1 else "(NoiseBackStep %s %d 1)" % (b, noise_idx)
        c = conf(rng)
        tracked("(noise-back-head %d)" % noise_idx,
                "(: (bench-noise-back-head %s %d) (Implication %s (BenchTarget %s %d)) (CTV (STV 1.0 %s) (STV 0.0 1.0)))" % (b, noise_idx, head_prem, b, path, c))
        meta("(bench-noise-back-meta %s %d 0)" % (b, noise_idx), "(BenchNoiseBackRule %s %d 0)" % (b, noise_idx))
        last = span - 1
        for step in range(1, last + 1):
            prem = "(NoiseBlocker %s %d)" % (b, noise_idx) if step == last else "(NoiseBackStep %s %d %d)" % (b, noise_idx, step + 1)
            c = conf(rng)
            tracked("(noise-back-rule %d %d)" % (noise_idx, step),
                    "(: (bench-noise-back-rule %s %d %d) (Implication %s (NoiseBackStep %s %d %d)) (CTV (STV 1.0 %s) (STV 0.0 1.0)))" % (b, noise_idx, step, prem, b, noise_idx, step, c))
            meta("(bench-noise-back-meta %s %d %d)" % (b, noise_idx, step), "(BenchNoiseBackRule %s %d %d)" % (b, noise_idx, step))
        noise_idx += 1
        remaining -= span
    noise_idx, remaining = 1 + back_budget, fwd_budget
    while remaining > 0:
        span = min(remaining, max(1, args.forward_chain_len))
        for step in range(1, span + 1):
            if step == 1:
                prem = "(BenchFact %s %d %d)" % (b, cycle1(noise_idx, P), cycle1(noise_idx, W ** D))
            else:
                prem = "(NoiseForward %s %d %d)" % (b, noise_idx, step - 1)
            concl = "(NoiseDeadEnd %s %d)" % (b, noise_idx) if step == span else "(NoiseForward %s %d %d)" % (b, noise_idx, step)
            c = conf(rng)
            tracked("(noise-forward-rule %d %d)" % (noise_idx, step),
                    "(: (bench-noise-forward-rule %s %d %d) (Implication %s %s) (CTV (STV 1.0 %s) (STV 0.0 1.0)))" % (b, noise_idx, step, prem, concl, c))
            meta("(bench-noise-forward-meta %s %d %d)" % (b, noise_idx, step), "(BenchNoiseForwardRule %s %d %d)" % (b, noise_idx, step))
        noise_idx += 1
        remaining -= span
    out.append(";; %d compileadd statements (true %d, noise %d: backward %d forward %d)\n" % (
        len(stmts), true_count, noise_total, back_budget, fwd_budget))
    out.extend(stmts)
    out.append("\n")
    for path in range(1, P + 1):
        out.append("!(collapse (query %d %s (: $prf (BenchTarget %s %d) $tv)))\n" % (args.steps, kb, b, path))
    return "".join(out)


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="kind", required=True)
    w = sub.add_parser("w2-wmtm")
    w.add_argument("--fixture", required=True)
    w.add_argument("--fixture-sha256", default="")
    w.add_argument("--seed", type=int, default=20261124)
    w.add_argument("--classes", type=int, default=24)
    w.add_argument("--entities", type=int, default=40)
    w.add_argument("--rules", type=int, default=10)
    w.add_argument("--goals", type=int, default=10)
    w.add_argument("--negatives", type=int, default=4)
    w.add_argument("--steps", type=int, default=100)
    w.add_argument("--kb", default="wmtmKb")
    g = sub.add_parser("w3-benchgen")
    g.add_argument("--seed", type=int, default=20261124)
    g.add_argument("--bench", default="s0Bench")
    g.add_argument("--kb", default="kb")
    g.add_argument("--depth", type=int, default=3)
    g.add_argument("--width", type=int, default=3)
    g.add_argument("--paths", type=int, default=3)
    g.add_argument("--noise-factor", type=int, default=10)
    g.add_argument("--backward-ratio", type=int, default=50)
    g.add_argument("--backward-chain-len", type=int, default=3)
    g.add_argument("--forward-chain-len", type=int, default=2)
    g.add_argument("--steps", type=int, default=1000)
    ap.add_argument("--out", default="-")
    args = ap.parse_args()
    text = gen_wmtm(args) if args.kind == "w2-wmtm" else gen_benchgen(args)
    if args.out == "-":
        sys.stdout.write(text)
    else:
        open(args.out, "w").write(text)


if __name__ == "__main__":
    main()
