#!/usr/bin/env python3
"""S2: coverage of run time and search time by the compiled functions (ESTIMATE), set against S1's ceiling.

  coverage.py --s1-prof evidence/s1-2026-11-24/prof-pilot --s1-step4 evidence/s1-2026-11-24/step4/step4.json \
              --e2e E2E_DIR [--run 1] --out-md OUT.md --out-json OUT.json [--check]

Measured inputs:
  - S1's profiled runs of the same workloads on CeTTa without S2 (prof-pilot, run 1, fnprof.json summed over the
    workload's files): each function's self time (the profiler's self_ns: time in the function's own frame, which
    includes callees that CeTTa runs without a profiler frame of their own) and the run's total;
  - S1's step-4 sample counts: search-episode self samples / all samples (the search share of the run);
  - S2's on-arm counters (E2E_DIR/on/W/*.rRUN.fns.json, summed over files): calls offered and answered per function.
Estimate: the run time now executed by compiled code = sum over compiled entry functions f of
self_ns(f) x answered(f) / offered(f), i.e. f's own CeTTa time, scaled by the fraction of f's calls the compiled code
answers.  Assumes answered calls cost what an average call of f costs in CeTTa; that callees answered inside a compiled
call are inside f's self time; and ignores the guard and hook costs.  It is the share of time handed to compiled
code, not the time saved (compiled code is not free).
S1's ceiling (docs/S1_HOT_SITES.md 5.4, full native episode): saved of run 11.7-63.9% depending on workload.
"""
import argparse
import glob
import json
import os
import sys

W = ["w1-examples", "w2-wmtm", "w3-benchgen"]
CEILING = {"w1-examples": (24.3, 63.9, 1.32, 2.77), "w2-wmtm": (21.5, 59.1, 1.27, 2.45),
           "w3-benchgen": (11.7, 31.3, 1.13, 1.46)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--s1-prof", required=True)
    ap.add_argument("--s1-step4", required=True)
    ap.add_argument("--e2e", required=True)
    ap.add_argument("--run", type=int, default=1)
    ap.add_argument("--out-md", required=True)
    ap.add_argument("--out-json", required=True)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    step4 = json.load(open(a.s1_step4))
    J = {}
    L = ["# S2 coverage of run and search time by compiled code (ESTIMATE; generated by bench/s2/coverage.py)", "",
         "Per compiled entry function: S1's CeTTa self time for it (prof-pilot run 1, fnprof self_ns) x the fraction "
         "of its calls S2's compiled code answered (on arm, run %d). Share of time handed to compiled code, not time "
         "saved. Search share of the run from S1 step 4 (search self samples / samples)." % a.run, ""]
    for w in W:
        total = 0
        self_ns = {}
        for p in sorted(glob.glob(os.path.join(a.s1_prof, w, "*.fnprof.json"))):
            d = json.load(open(p))
            total += d["total_ns"]
            for f in d["functions"]:
                self_ns[f["head"]] = self_ns.get(f["head"], 0) + f["self_ns"]
        cnt = {}
        files = sorted(glob.glob(os.path.join(a.e2e, "on", w, "*.r%d.fns.json" % a.run)))
        for p in files:
            for fn, v in json.load(open(p))["functions"].items():
                c = cnt.setdefault(fn, [0, 0])
                c[0] += v["offered"]
                c[1] += v["answered"]
        s4 = step4[w]
        search_share = s4["search_self"] / s4["samples_without_profiler"]
        rows = []
        cov = 0.0
        for fn in sorted(cnt, key=lambda f: -self_ns.get(f, 0)):
            off, ans = cnt[fn]
            if not off:
                continue
            frac = ans / off
            est = self_ns.get(fn, 0) * frac
            cov += est
            rows.append({"function": fn, "s1_self_ns": self_ns.get(fn, 0), "offered": off, "answered": ans,
                         "answered_fraction": frac, "est_ns": est})
        run_share = cov / total if total else 0.0
        all_self = sum(self_ns.get(r["function"], 0) for r in rows) / total if total else 0.0
        J[w] = {"s1_total_ns": total, "search_self_share": search_share, "rows": rows,
                "compiled_functions_self_share_of_run": all_self,
                "est_run_share_compiled": run_share, "est_search_share_compiled": run_share / search_share,
                "s1_ceiling_saved_of_run_pct": CEILING[w][:2], "s1_ceiling_speedup": CEILING[w][2:],
                "e2e_files": len(files)}
        L += ["## %s" % w, "",
              "| function | S1 CeTTa self s | share of run | calls offered (S2 on) | answered | answered % | est. s now compiled |",
              "|---|---|---|---|---|---|---|"]
        for r in rows:
            L.append("| %s | %.2f | %.2f%% | %d | %d | %.1f%% | %.2f |" % (
                r["function"], r["s1_self_ns"] / 1e9, 100 * r["s1_self_ns"] / total, r["offered"], r["answered"],
                100 * r["answered_fraction"], r["est_ns"] / 1e9))
        L += ["", "- all compiled functions' own CeTTa time: %.1f%% of the run" % (100 * all_self),
              "- estimated share of the run now executed by compiled code: **%.1f%%**; of search-episode self time "
              "(search self = %.1f%% of the run): **%.1f%%**" % (100 * run_share, 100 * search_share,
                                                                 100 * run_share / search_share),
              "- S1's ceiling for compiling the whole search episode: %.1f-%.1f%% of the run saved (%.2f-%.2fx)" %
              CEILING[w], ""]
    md = "\n".join(L) + "\n"
    js = json.dumps(J, indent=1, sort_keys=True) + "\n"
    if a.check:
        ok = open(a.out_md).read() == md and open(a.out_json).read() == js
        print("recompute: %s" % ("identical" if ok else "DIFFERS"))
        return 0 if ok else 1
    open(a.out_md, "w").write(md)
    open(a.out_json, "w").write(js)
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
