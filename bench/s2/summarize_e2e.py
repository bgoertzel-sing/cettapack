#!/usr/bin/env python3
"""S2 step 3: summarise the end-to-end runs (bench/s2/run_e2e.sh) into OUT/summary.md and OUT/summary.json.

  summarize_e2e.py E2E_DIR           # writes E2E_DIR/summary.md, summary.json
  summarize_e2e.py E2E_DIR --check   # recomputes and compares byte for byte (exit 1 on a difference)

Per workload and arm (base, off, on), over runs: user and wall seconds (sum over the workload's files in that run),
peak RSS (the largest file's maximum resident set in that run), median (min-max); paired ratios run by run (the
three arms of round r ran back to back); answers (every run's check line: exit 0, stdout byte-identical to S0's base
stdout of the same file, no failed test); the compiled functions' counters in the on arm (*.fns.json).
Noise criterion (stated in the output): the gain on a workload beats run-to-run noise only if every paired on/off
user ratio is below 1 (all runs faster; with 5 runs a sign test gives p = 1/32 one-sided) and the median paired
ratio is below the smallest off/base ratio's distance from 1 subtracted from 1 (the gain exceeds what two builds of
the same code, off and base, differ by).
"""
import glob
import json
import os
import re
import statistics
import sys

WORKLOADS = ["w1-examples", "w2-wmtm", "w3-benchgen"]
ARMS = ["base", "off", "on"]


def med(xs):
    return statistics.median(xs) if xs else float("nan")


def rng(xs, fmt="%.3f"):
    if not xs:
        return "-"
    return (fmt + " (" + fmt + "-" + fmt + ")") % (med(xs), min(xs), max(xs))


def load(d):
    runs = {}  # (arm, workload, run) -> dict
    checks = {}
    sites = {}
    for arm in ARMS:
        for w in WORKLOADS:
            for t in sorted(glob.glob(os.path.join(d, arm, w, "*.time"))):
                base = t[:-len(".time")]
                name, r = re.match(r"(.*)\.r(\d+)$", os.path.basename(base)).groups()
                r = int(r)
                parts = open(t).read().split()
                # /usr/bin/time -f '%e %U %S %M' (last line; earlier lines may hold a command's own messages)
                last = open(t).read().strip().split("\n")[-1].split()
                e, u, s, m = float(last[0]), float(last[1]), float(last[2]), int(last[3])
                key = (arm, w, r)
                agg = runs.setdefault(key, {"user": 0.0, "wall": 0.0, "rss_kib": 0, "files": 0})
                agg["user"] += u
                agg["wall"] += e
                agg["rss_kib"] = max(agg["rss_kib"], m)
                agg["files"] += 1
                chk = open(base + ".check").read().strip()
                checks.setdefault((arm, w), []).append((name, r, chk))
                sj = base + ".fns.json"
                if arm == "on" and os.path.exists(sj):
                    sites.setdefault((w, r), []).append(json.load(open(sj)))
    return runs, checks, sites


def summarise(d):
    runs, checks, sites = load(d)
    L = ["# S2 end-to-end runs: w1-w3, packs off and on (generated by bench/s2/summarize_e2e.py; do not edit)\n",
         "Arms: base = S0's base build (a9b3a811 + 0001-0004); off = the S2 build (0001-0008 + the compiled functions) "
         "with CETTA_S2_FNS=0 CETTA_S1_SITES=0; on = the same binary with CETTA_S2_FNS=1 CETTA_S1_SITES=0. Round r ran every workload in the three "
         "arms back to back, arm order rotating by round. Times are sums over the workload's files per run; peak RSS is "
         "the largest file's maximum resident set in the run. Values: median (min-max) over runs.\n"]
    J = {"workloads": {}}
    L.append("## Answers\n")
    L.append("| workload | arm | runs x files | exit 0 | stdout = S0 base | failed tests |")
    L.append("|---|---|---|---|---|---|")
    all_ok = True
    for w in WORKLOADS:
        for arm in ARMS:
            c = checks.get((arm, w), [])
            ex = sum(1 for _, _, k in c if k.startswith("exit=0 "))
            same = sum(1 for _, _, k in c if "answers_vs_s0_base=same" in k)
            fails = sum(int(re.search(r"failed_tests=(\d+)", k).group(1)) for _, _, k in c)
            nruns = len({r for _, r, _ in c})
            nfiles = len({n for n, _, _ in c})
            all_ok &= ex == len(c) and same == len(c) and fails == 0 and len(c) > 0
            L.append("| %s | %s | %d x %d | %d/%d | %d/%d | %d |" % (w, arm, nruns, nfiles, ex, len(c), same, len(c), fails))
    L.append("\nEvery run of every arm exits 0 with S0's answers and no failed test: **%s**.\n" % ("yes" if all_ok else "NO"))
    J["answers_all_identical"] = all_ok
    L.append("## End-to-end time and peak memory\n")
    L.append("| workload | arm | runs | user s | wall s | peak RSS MiB |")
    L.append("|---|---|---|---|---|---|")
    for w in WORKLOADS:
        J["workloads"][w] = {}
        for arm in ARMS:
            rs = sorted(r for (a, ww, r) in runs if a == arm and ww == w)
            u = [runs[(arm, w, r)]["user"] for r in rs]
            e = [runs[(arm, w, r)]["wall"] for r in rs]
            m = [runs[(arm, w, r)]["rss_kib"] / 1024.0 for r in rs]
            L.append("| %s | %s | %d | %s | %s | %s |" % (w, arm, len(rs), rng(u, "%.2f"), rng(e, "%.2f"), rng(m, "%.0f")))
            J["workloads"][w][arm] = {"runs": rs, "user": u, "wall": e, "rss_mib": m}
    L.append("\n## Paired ratios (run r of each arm against run r of another)\n")
    L.append("| workload | runs | on/off user | on/off wall | off/base user | on/base user | on/off peak RSS |")
    L.append("|---|---|---|---|---|---|---|")
    for w in WORKLOADS:
        W = J["workloads"][w]
        rs = sorted(set(W["on"]["runs"]) & set(W["off"]["runs"]) & set(W["base"]["runs"]))

        def ratio(a, b, k):
            return [W[a][k][W[a]["runs"].index(r)] / W[b][k][W[b]["runs"].index(r)] for r in rs]
        on_off_u, on_off_e = ratio("on", "off", "user"), ratio("on", "off", "wall")
        off_base, on_base, rss = ratio("off", "base", "user"), ratio("on", "base", "user"), ratio("on", "off", "rss_mib")
        L.append("| %s | %d | %s | %s | %s | %s | %s |" % (w, len(rs), rng(on_off_u), rng(on_off_e), rng(off_base),
                                                         rng(on_base), rng(rss)))
        W["paired"] = {"runs": rs, "on_off_user": on_off_u, "on_off_wall": on_off_e, "off_base_user": off_base,
                       "on_base_user": on_base, "on_off_rss": rss}
    L.append("\n## Does the gain beat run-to-run noise?\n")
    L.append("Criterion: every paired on/off user ratio < 1, and median on/off < 1 - max(|off/base - 1|) (the gain is "
             "larger than the largest difference between two builds of the same code).\n")
    L.append("| workload | on/off user, every run < 1 | median on/off | noise floor 1 - max abs(off/base - 1) | beats noise |")
    L.append("|---|---|---|---|---|")
    for w in WORKLOADS:
        P = J["workloads"][w]["paired"]
        if not P["runs"]:
            continue
        allbelow = all(x < 1.0 for x in P["on_off_user"])
        floor = 1.0 - max(abs(x - 1.0) for x in P["off_base_user"])
        m = med(P["on_off_user"])
        beats = allbelow and m < floor
        P["beats_noise"] = beats
        L.append("| %s | %s | %.3f | %.3f | %s |" % (w, "yes" if allbelow else "no", m, floor, "**yes**" if beats else "**no**"))
    L.append("\n## The compiled functions in the on arm (counters summed over the workload's files)\n")
    L.append("| workload | runs | function | offered | answered | declined: guard invalid | declined: call outside the code | same in every run |")
    L.append("|---|---|---|---|---|---|---|---|")
    R = ["\n### Decline reasons (on arm, first run, summed over files)\n", "| workload | reason | calls |", "|---|---|---|"]
    for w in WORKLOADS:
        per_run = {}
        reasons = {}
        for (ww, r), lst in sites.items():
            if ww != w:
                continue
            tot = {}
            rs = {}
            for s in lst:
                for fn, v in s["functions"].items():
                    t = tot.setdefault(fn, {"offered": 0, "answered": 0, "declined_invalid": 0, "declined_call": 0})
                    for k in t:
                        t[k] += v[k]
                for k, v in s["reasons"].items():
                    rs[k] = rs.get(k, 0) + v
            per_run[r] = tot
            reasons[r] = rs
        if not per_run:
            L.append("| %s | 0 | - | - | - | - | - | - |" % w)
            continue
        first = per_run[min(per_run)]
        same = all(v == first for v in per_run.values()) and all(v == reasons[min(reasons)] for v in reasons.values())
        for fn in sorted(first, key=lambda f: -first[f]["offered"]):
            v = first[fn]
            if not v["offered"]:
                continue
            L.append("| %s | %d | %s | %d | %d | %d | %d | %s |" % (w, len(per_run), fn, v["offered"], v["answered"],
                                                                v["declined_invalid"], v["declined_call"], "yes" if same else "NO"))
        for k, v in sorted(reasons[min(reasons)].items(), key=lambda kv: -kv[1]):
            R.append("| %s | %s | %d |" % (w, k, v))
        J["workloads"][w]["functions"] = {"per_run_identical": same, "counters": first, "reasons": reasons[min(reasons)]}
    L += R
    return "\n".join(L) + "\n", json.dumps(J, indent=1, sort_keys=True) + "\n"


def main():
    d = sys.argv[1]
    md, js = summarise(d)
    if "--check" in sys.argv[2:]:
        ok = open(os.path.join(d, "summary.md")).read() == md and open(os.path.join(d, "summary.json")).read() == js
        print("recompute: %s" % ("identical" if ok else "DIFFERS"))
        return 0 if ok else 1
    open(os.path.join(d, "summary.md"), "w").write(md)
    open(os.path.join(d, "summary.json"), "w").write(js)
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
