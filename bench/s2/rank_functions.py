#!/usr/bin/env python3
"""S2 step 1: S1's ranked list of the search functions (rows of backward_chainer.metta / backward_proof_store.metta)
by self samples, pooled over w1-w3 (S1 prof-pilot run 1, symbolised), with the profiler's calls and self ns.

  rank_functions.py --image IMAGE --symdir SYMDIR --fnprof-root EVIDENCE/prof-pilot --out-md OUT.md --out-json OUT.json
"""
import argparse, collections, glob, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)) + "/../s1")
import step4_search as s4  # noqa

ap = argparse.ArgumentParser()
ap.add_argument("--image", required=True)
ap.add_argument("--symdir", required=True)
ap.add_argument("--fnprof-root", required=True)
ap.add_argument("--out-md", required=True)
ap.add_argument("--out-json", required=True)
a = ap.parse_args()
mm = s4.module_map(a.image)
W = ["w1-examples", "w2-wmtm", "w3-benchgen"]
self_s = {w: collections.Counter() for w in W}
tot = {w: 0 for w in W}
search_tot = {w: 0 for w in W}
for w in W:
    for p in sorted(glob.glob(os.path.join(a.symdir, w + ".*.sym.json"))):
        d = json.load(open(p))
        for s in d["samples"]:
            if s4.sc.categorise(s["stack"]) == "profiler":
                continue
            tot[w] += 1
            row = s["rows"][0]
            if s4.row_module(row, mm) in s4.SEARCH_MODULES:
                search_tot[w] += 1
                self_s[w][row] += 1
calls = {w: collections.Counter() for w in W}
ns = {w: collections.Counter() for w in W}
for w in W:
    for p in sorted(glob.glob(os.path.join(a.fnprof_root, w, "*.fnprof.json"))):
        for f in json.load(open(p))["functions"]:
            calls[w][f["head"]] += f["calls"]
            ns[w][f["head"]] += f["self_ns"]
pooled = collections.Counter()
for w in W:
    for r, n in self_s[w].items():
        pooled[r] += n / search_tot[w]  # equal weight per workload: mean share of search self
rank = sorted(pooled, key=lambda r: -pooled[r])
rows = []
cum = 0.0
for i, r in enumerate(rank):
    share = pooled[r] / len(W)
    cum += share
    rows.append({"rank": i + 1, "row": r, "module": s4.row_module(r, mm), "mean_share": share, "cum": cum,
                 **{w + ".self_samples": self_s[w][r] for w in W},
                 **{w + ".share": self_s[w][r] / search_tot[w] for w in W},
                 **{w + ".calls": calls[w][r] for w in W},
                 **{w + ".self_ns": ns[w][r] for w in W}})
json.dump({"search_self_samples": search_tot, "samples": tot, "rows": rows}, open(a.out_json, "w"), indent=1)
L = ["# S2: S1's search functions ranked by self samples (generated by bench/s2/rank_functions.py)", "",
     "Search rows = rows of backward_chainer.metta / backward_proof_store.metta (S1 step 4). Share = share of the "
     "workload's search self samples; mean = unweighted mean over w1-w3; cum = cumulative mean. Calls and self ms "
     "from the same runs' fnprof.json (S1 prof-pilot run 1).", "",
     "| # | row | mean % | cum % | w1 % | w2 % | w3 % | calls w1 | calls w2 | calls w3 | self us/call (w1, w2, w3) |",
     "|---|---|---|---|---|---|---|---|---|---|---|"]
for x in rows:
    if x["cum"] > 0.95 and x["rank"] > 30:
        break
    upc = ", ".join("%.0f" % (x[w + ".self_ns"] / x[w + ".calls"] / 1000) if x[w + ".calls"] else "-" for w in W)
    L.append("| %d | %s | %.1f | %.1f | %.1f | %.1f | %.1f | %d | %d | %d | %s |" % (
        x["rank"], x["row"], 100 * x["mean_share"], 100 * x["cum"], *(100 * x[w + ".share"] for w in W),
        *(x[w + ".calls"] for w in W), upc))
n90 = next(x["rank"] for x in rows if x["cum"] >= 0.90)
L += ["", "Rows holding 90%% of mean search self time: %d." % n90]
open(a.out_md, "w").write("\n".join(L) + "\n")
print("\n".join(L))
