#!/usr/bin/env python3
"""S2: coverage measured with the sampler (fnsprof build: CETTA_FNPROF=1, -g, one SIGPROF sample per ms of CPU).

  compiled_samples.py SPROF_DIR [--binary build/s2/cetta-fnsprof/cetta] [--image IMAGE] [--check]

SPROF_DIR/{poff,pon}/W/*.samples.txt.gz (+ .fnprof.json) from bench/s2/run_workloads.sh poff|pon.  Each run is
symbolised with bench/s1/analyze_samples.py (addr2line on the -g binary).  Per workload and arm, over samples without
the profiler's own (bench/s1/sample_categories.py "profiler"):
  - compiled: samples with a frame of the compiled code or its hook on the native stack (fn_*, s2_*, cetta_s2_fns_*,
    petta_machine_try_s2_fn: cettapack's src/cpk_s2_fns.c and 0008's hook), i.e. time spent inside compiled calls,
    guards and the CeTTa helpers they call;
  - fn rows: samples whose leaf profiler row is one of the compiled functions (CeTTa running them: the residual, and
    in the off arm all of them);
  - search: samples whose leaf row belongs to the search episode (S1 step 4: backward_chainer.metta,
    backward_proof_store.metta).
Writes SPROF_DIR/samples_compiled.md and .json (--check: recompute and compare byte for byte).
"""
import argparse
import glob
import json
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "s1"))
import sample_categories as sc  # noqa: E402
import step4_search as s4  # noqa: E402

W = ["w1-examples", "w2-wmtm", "w3-benchgen"]
FNS = {"make-and-bundle", "and-bundle-premises", "frontier-remaining-score", "frontier-pool-potential", "expr-arity",
       "premises-expected-confidence", "premises-expected-confidence-step", "term-confidence", "proof-score",
       "tv-confidence", "proof-output-key-by-id", "proof-output-atom-by-id", "proof-output-atom",
       "candidate-output-key"}
COMPILED = re.compile(r"^(fn_[a-z_]+|s2_[a-z_]+|cetta_s2_fns_[a-z_]+|petta_machine_try_s2_fn)$")


def in_compiled(stack):
    for frame in stack:
        for fn in frame:
            if COMPILED.match(fn.split("@")[0]):
                return True
    return False


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("sprof")
    ap.add_argument("--binary", default=os.path.join(HERE, "..", "..", "build", "s2", "cetta-fnsprof", "cetta"))
    ap.add_argument("--image", default=None)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    image = a.image
    tmp = tempfile.mkdtemp()
    if not image:
        image = os.path.join(tmp, "image")
        os.makedirs(image)
        scratch = os.environ.get("S0_SCRATCH", os.path.join(HERE, "..", "..", "..", "..", "scratch"))
        repo = os.environ.get("CHAINER_REPO", os.path.join(scratch, "survey", "PeTTaChainer"))
        subprocess.check_call("git -C '%s' archive b0e24f9b9d7106ccabf51917f1703abf3ab8c570 pettachainer/metta | "
                              "tar -x -C '%s' --strip-components=2" % (repo, image), shell=True)
    mm = s4.module_map(image)
    J = {}
    L = ["# S2 coverage measured with the sampler (generated by bench/s2/compiled_samples.py; do not edit)", "",
         "fnsprof build (0001-0008, CETTA_FNPROF=1, -g), one run per workload and arm, packs off (poff) and on (pon). "
         "Shares of samples without the profiler's own. compiled = a frame of the compiled code or its hook on the "
         "native stack; fn rows = leaf profiler row is a compiled function (CeTTa running it); search = leaf row in "
         "the search episode (S1 step 4).", "",
         "| workload | arm | samples | search rows | compiled code | compiled, of search | fn rows (CeTTa) | compiled + fn rows |",
         "|---|---|---|---|---|---|---|---|"]
    for w in W:
        J[w] = {}
        for arm in ("poff", "pon"):
            n = srch = comp = comp_srch = fnrows = 0
            runs = sorted(glob.glob(os.path.join(a.sprof, arm, w, "*.samples.txt.gz")))
            for p in runs:
                fp = p[:-len(".samples.txt.gz")] + ".fnprof.json"
                out = os.path.join(tmp, "s.json")
                subprocess.check_call([sys.executable, os.path.join(HERE, "..", "s1", "analyze_samples.py"),
                                       "symbolise", p, fp, "--binary", a.binary, "--out", out],
                                      stdout=subprocess.DEVNULL)
                for s in json.load(open(out))["samples"]:
                    if sc.categorise(s["stack"]) == "profiler":
                        continue
                    n += 1
                    row = s["rows"][0] if s["rows"] else ""
                    is_s = s4.row_module(row, mm) in s4.SEARCH_MODULES
                    is_c = in_compiled(s["stack"])
                    srch += is_s
                    comp += is_c
                    comp_srch += is_c and is_s
                    fnrows += (row in FNS) and not is_c
            J[w][arm] = {"runs": len(runs), "samples": n, "search": srch, "compiled": comp,
                         "compiled_in_search": comp_srch, "fn_rows": fnrows}
            pc = lambda x: "%.2f%%" % (100.0 * x / n) if n else "-"
            L.append("| %s | %s | %d | %s | %s | %s | %s | %s |" % (
                w, arm[1:], n, pc(srch), pc(comp), "%.2f%%" % (100.0 * comp_srch / srch) if srch else "-",
                pc(fnrows), pc(comp + fnrows)))
    L += ["", "Reading: in the on arm, \"compiled code\" is the share of the run executed by compiled functions (with "
          "their guards and the CeTTa helpers they call); \"compiled, of search\" the share of search-episode samples. "
          "The off arm's \"fn rows\" is what CeTTa spends on the same functions' own rows; comparing it with the on "
          "arm's \"compiled + fn rows\" (compiled code plus the residual calls) shows what compiling them changed."]
    md = "\n".join(L) + "\n"
    js = json.dumps(J, indent=1, sort_keys=True) + "\n"
    mdp, jsp = os.path.join(a.sprof, "samples_compiled.md"), os.path.join(a.sprof, "samples_compiled.json")
    if a.check:
        ok = open(mdp).read() == md and open(jsp).read() == js
        print("recompute: %s" % ("identical" if ok else "DIFFERS"))
        return 0 if ok else 1
    open(mdp, "w").write(md)
    open(jsp, "w").write(js)
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
