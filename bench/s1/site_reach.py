#!/usr/bin/env python3
"""S1: how much of each match site's time a compiled template could take, from the C-level samples.

fnspec's method (and S1's in-machine sites) keeps the matcher, CeTTa's own row source, and compiles what the
machine does per row after it: the condition, the template, the answer hand-back.  For every match-site row
(match@F S H) the samples are split by the innermost native function that names the row source:

  row source    the matcher and the relation cursor that produce rows (CeTTa's match choice and candidate
                unification, epoch matcher, space queries, open-equation relation cursor, Prolog predicate calls)
  per-row work  everything else in the row: condition and template evaluation, answer hand-back, glue

The per-row share is an upper bound on what compiling the condition and template can remove; the S1 site's
measured gain (fwd_register_base_rate_interest) is set against it.

  site_reach.py --sym W=GLOB [--sym ...] --classification evidence/s0-2026-11-24/classification.json --out-md OUT
"""
import argparse
import collections
import glob
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sample_categories as sc  # noqa: E402

ROW_SOURCE = re.compile(
    r"petta_machine_start_match_choice_policy|petta_machine_match_candidate|petta_semantics_match_cons_constraint|"
    r"petta_machine_match_epoch_candidate|match_atoms_epoch|petta_machine_start_space_query|"
    r"petta_machine_try_ready_relation_invocation|^oem_|cetta_open_equation_cursor|petta_match_source_call|"
    r"space_query|space_subst|petta_machine_start_predicate|@libswipl|^PL_|^pl_|native_query_run|"
    r"petta_machine_open_resume|petta_machine_start_open_answers|petta_machine_start_open_term_answers")


def part(stack):
    for frame in sc.trim(stack):
        for fn in frame:
            fn = sc.norm(fn)
            if fn.startswith("fnprof_"):
                return "profiler"
            if ROW_SOURCE.search(fn):
                return "row source"
    return "per-row work"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sym", action="append", required=True)
    ap.add_argument("--classification")
    ap.add_argument("--out-md", required=True)
    ap.add_argument("--out-json")
    a = ap.parse_args()
    cls = {}
    if a.classification:
        c = json.load(open(a.classification))
        for k, v in (c.get("rows") or c).items() if isinstance(c, dict) else []:
            if isinstance(v, dict):
                cls[k] = v.get("class") or v.get("kind")
    out = {}
    L = ["# S1: what compiling a match site's template could take (generated by bench/s1/site_reach.py)\n",
         "Per match-site row: samples (profiler's own removed), split into the row source (matcher, relation cursor; "
         "kept by the method) and per-row work (condition, template, hand-back, glue: the upper bound on what "
         "compiling them removes). Shares are of the workload's samples without the profiler's.\n"]
    for spec in a.sym:
        w, _, g = spec.partition("=")
        per = collections.defaultdict(collections.Counter)
        total = 0
        for p in sorted(glob.glob(g)):
            for s in json.load(open(p))["samples"]:
                k = part(s["stack"])
                if k == "profiler":
                    continue
                total += 1
                r = s["rows"][0]
                if r.startswith("match@"):
                    per[r][k] += 1
        rows = sorted(per.items(), key=lambda kv: -sum(kv[1].values()))
        out[w] = {"total": total, "rows": {r: dict(c) for r, c in rows}}
        L.append("\n## %s (%d samples)\n" % (w, total))
        L.append("| match site | S0 class | samples % | row source % | per-row work % (bound) |")
        L.append("|---|---|---|---|---|")
        sums = collections.Counter()
        for r, c in rows:
            n = sum(c.values())
            klass = cls.get(r, "")
            sums["all"] += n
            sums["src"] += c["row source"]
            sums["work"] += c["per-row work"]
            if klass == "extension":
                sums["ext_work"] += c["per-row work"]
                sums["ext"] += n
            if n * 1000 < total * 2:  # rows under 0.2% are summed only
                continue
            L.append("| %s | %s | %.2f | %.2f | %.2f |" % (r[:110], klass, 100.0 * n / total,
                                                          100.0 * c["row source"] / total, 100.0 * c["per-row work"] / total))
        L.append("| all match-site rows | | %.2f | %.2f | %.2f |" % (100.0 * sums["all"] / total, 100.0 * sums["src"] / total,
                                                                   100.0 * sums["work"] / total))
        if cls:
            L.append("| rows S0 classed 'extension' | | %.2f | | %.2f |" % (100.0 * sums["ext"] / total,
                                                                          100.0 * sums["ext_work"] / total))
        out[w]["sums"] = {k: 100.0 * v / total for k, v in sums.items()}
    open(a.out_md, "w").write("\n".join(L) + "\n")
    if a.out_json:
        json.dump(out, open(a.out_json, "w"), indent=1, sort_keys=True)
    print("\n".join(L))


if __name__ == "__main__":
    main()
