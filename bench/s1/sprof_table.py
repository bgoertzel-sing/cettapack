#!/usr/bin/env python3
"""S1: the compiled site's own row in the profiler, generic (sites off) against compiled (sites on), on the
sitesprof build (sites + CETTA_FNPROF=1), from bench/s1/run_workloads.sh sprof runs with SPROF_SITES=0 and =1.

The profiler opens the match-site frame before the hook (fnprof_match_site at the start of the match), so the row
match@forward-register-base-rate! &forward_base_rate_interest (...) holds the generic match's time with the sites off
and the compiled site's (guards, query, compiled rows, answer hand-back) with the sites on; its parent function's row
and the workload total are shown next to it.

  sprof_table.py SPROF_DIR [--check]     # SPROF_DIR/{off,on}/W/*.fnprof.json -> SPROF_DIR/summary.md
"""
import glob
import os
import statistics
import sys

import json

WORKLOADS = ["w1-examples", "w2-wmtm", "w3-benchgen"]
ROW = "match@forward-register-base-rate! &forward_base_rate_interest (forward-base-rate-interest-row ...)"
PARENT = "forward-register-base-rate!"


def per_run(d, mode, w):
    runs = {}
    for p in glob.glob(os.path.join(d, mode, w, "*.fnprof.json")):
        r = int(p.rsplit(".r", 1)[1].split(".")[0])
        prof = json.load(open(p))
        acc = runs.setdefault(r, {"total": 0.0, "row": 0.0, "row_calls": 0, "parent_incl": 0.0})
        acc["total"] += prof["total_ns"] / 1e6
        for fn in prof["functions"]:
            if fn["head"] == ROW:
                acc["row"] += fn["self_ns"] / 1e6
                acc["row_calls"] += fn["calls"] + fn["frames"] * 0
            elif fn["head"] == PARENT:
                acc["parent_incl"] += fn["incl_ns"] / 1e6
    return runs


def rng(xs, f="%.1f"):
    if not xs:
        return "-"
    return (f + " (" + f + "-" + f + ")") % (statistics.median(xs), min(xs), max(xs))


def build(d):
    L = ["# S1: the compiled site's row, generic vs compiled (generated by bench/s1/sprof_table.py; do not edit)\n",
         "sitesprof build (0001-0007 + the compiled site, CETTA_FNPROF=1); off = CETTA_S1_SITES=0 (CeTTa runs the "
         "match), on = 1 (the compiled site answers it). ms, median (min-max) over runs; total = the profiler's wall "
         "total of the workload's files.\n",
         "| workload | runs | row self ms, off | row self ms, on | on/off (row) | parent incl. ms off | on | total ms off | total ms on | row share of total, off |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for w in WORKLOADS:
        off, on = per_run(d, "off", w), per_run(d, "on", w)
        rs = sorted(set(off) & set(on))
        if not rs:
            continue
        ro = [off[r]["row"] for r in rs]
        rn = [on[r]["row"] for r in rs]
        ratio = [on[r]["row"] / off[r]["row"] for r in rs if off[r]["row"] > 0]
        L.append("| %s | %d | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            w, len(rs), rng(ro), rng(rn), rng(ratio, "%.3f"),
            rng([off[r]["parent_incl"] for r in rs]), rng([on[r]["parent_incl"] for r in rs]),
            rng([off[r]["total"] for r in rs], "%.0f"), rng([on[r]["total"] for r in rs], "%.0f"),
            rng([100.0 * off[r]["row"] / off[r]["total"] for r in rs], "%.2f%%")))
    return "\n".join(L) + "\n"


def main():
    d = sys.argv[1]
    md = build(d)
    out = os.path.join(d, "summary.md")
    if "--check" in sys.argv:
        ok = open(out).read() == md
        print("recompute: %s" % ("identical" if ok else "DIFFERS"))
        return 0 if ok else 1
    open(out, "w").write(md)
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
