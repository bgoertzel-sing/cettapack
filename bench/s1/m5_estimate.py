#!/usr/bin/env python3
"""S1 step 4: what a native search episode (Ben's Milestone 5) could win, from the measured composition of the search
episode (bench/s1/step4_search.py's step4.json) and stated assumptions about what each mechanism removes.

MEASURED (step4.json): the share of run time inside the search episode (rows of backward_chainer.metta and
backward_proof_store.metta and everything they call), and its split into native cost categories.

ASSUMED (this file, the ASSUME table): for each category, the mechanism of Ben's note (cetta-guarded-
supercompilation-2026-07-06, section 11 and Milestone 5) that would replace it, and the fraction of the category's
time it would remove, low and high.  Two scenarios:

  named   M5 as the milestone names it: choice frames, trail/watermark rollback, scratch arenas, streamed answers,
          applied to the episode as CeTTa runs it now (the chainer's functions still interpreted).
  full    the whole native episode of section 11 as well: fixed rule dispatch and registers for bound variables
          (the chainer's search functions compiled), PathMap-backed fact iterators with exact rematch.

Saved fraction of the run f = episode share x sum(category share x fraction removed); end-to-end speedup 1/(1-f).
These are estimates under the stated assumptions, not measurements; the compiled code's own cost is taken as zero,
so the high column is an upper bound.

  m5_estimate.py STEP4_JSON [--out-md OUT]
"""
import json
import sys

# category -> (mechanism, named (low, high), full (low, high))
ASSUME = {
    "choice points, trail and backtracking": ("choice frames + trail/watermark rollback", (0.5, 1.0), (0.5, 1.0)),
    "allocation and freeing": ("scratch arena mark/reset", (0.3, 0.8), (0.3, 0.8)),
    "copying and instantiation": ("registers for bound variables (needs compiled functions)", (0.0, 0.0), (0.3, 0.8)),
    "equation selection and call preparation": ("fixed rule dispatch (needs compiled functions)", (0.0, 0.0), (0.5, 0.9)),
    "goal dispatch and evaluation": ("compiled control (needs compiled functions)", (0.0, 0.0), (0.5, 0.9)),
    "matching, unification and fact iteration": ("PathMap fact iterators + exact rematch", (0.0, 0.0), (0.0, 0.5)),
    "hashing, interning and term universe": ("fewer fresh terms (follows from the above)", (0.0, 0.0), (0.0, 0.5)),
    "prolog (SWI-Prolog and the foreign boundary)": ("not M5 (the chainer's Prolog heaps; a native heap is another step)", (0.0, 0.0), (0.0, 0.0)),
    "space mutation (add/remove atoms)": ("not removed (the search state is in spaces)", (0.0, 0.0), (0.0, 0.0)),
    "grounded ops and arithmetic": ("not removed (TV formulas; M6's unboxed kernels)", (0.0, 0.0), (0.0, 0.0)),
    "other machine": ("-", (0.0, 0.0), (0.0, 0.0)),
}


def main():
    d = json.load(open(sys.argv[1]))
    out = sys.argv[sys.argv.index("--out-md") + 1] if "--out-md" in sys.argv else None
    L = ["# S1 step 4: Milestone 5 estimate (generated by bench/s1/m5_estimate.py from step4.json; ESTIMATE, not measured)\n",
         "Measured inputs: the episode's share of run time and its native composition (step4.md). Assumed: the fraction "
         "of each category a mechanism removes (table below). The compiled code's own cost is taken as zero.\n",
         "| category | mechanism | removed, named M5 | removed, full native episode |", "|---|---|---|---|"]
    for c, (m, a, b) in ASSUME.items():
        L.append("| %s | %s | %d-%d%% | %d-%d%% |" % (c, m, a[0] * 100, a[1] * 100, b[0] * 100, b[1] * 100))
    L += ["", "| workload | episode share (measured) | named M5: saved of run | speedup | full episode: saved of run | speedup |",
          "|---|---|---|---|---|---|"]
    res = {}
    for w, r in d.items():
        base = r["samples_without_profiler"]
        ep = r["search_incl"] / base
        comp = {c: n / r["search_incl"] for c, n in r["search_incl_categories"].items()}
        row = {}
        for sc, k in (("named", 1), ("full", 2)):
            lo = ep * sum(comp.get(c, 0.0) * v[k][0] for c, v in ASSUME.items())
            hi = ep * sum(comp.get(c, 0.0) * v[k][1] for c, v in ASSUME.items())
            row[sc] = (lo, hi)
        res[w] = {"episode": ep, **{k: list(v) for k, v in row.items()}}
        L.append("| %s | %.1f%% | %.1f-%.1f%% | %.2f-%.2fx | %.1f-%.1f%% | %.2f-%.2fx |" % (
            w, 100 * ep, 100 * row["named"][0], 100 * row["named"][1], 1 / (1 - row["named"][0]), 1 / (1 - row["named"][1]),
            100 * row["full"][0], 100 * row["full"][1], 1 / (1 - row["full"][0]), 1 / (1 - row["full"][1])))
    text = "\n".join(L) + "\n"
    if out:
        open(out, "w").write(text)
    print(text)


if __name__ == "__main__":
    main()
