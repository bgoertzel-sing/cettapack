#!/usr/bin/env python3
"""cetta-internals P: CeTTa's own runtime counters (ENABLE_RUNTIME_STATS=1, --emit-runtime-stats) on w1-w3.

  stats_report.py RUNDIR [--json OUT.json] [--md OUT.md] [--grep REGEX ...]

RUNDIR holds WORKLOAD/NAME.stats.rN.stderr (bench/p/run_workloads.sh, BUILD=stats).  Counters are summed over a
workload's files per run; the counters are deterministic here (single-threaded runs), so the runs should agree; the
report gives run 1 and flags any counter that differs between runs.  --grep selects counters for the table (all
nonzero counters go to the JSON).
"""
import argparse
import collections
import glob
import json
import os
import re

WORKLOADS = ["w1-examples", "w2-wmtm", "w3-benchgen"]
LINE = re.compile(r"^runtime-counter (\S+) (-?\d+)$")
DEFAULT = [r"PREPARED_PURE_CALL_(ADMISSION|COMMIT|DECLINE|COMPILE_ATTEMPT|COMPILE_DECLINE|PROGRAM_CACHE_HIT|"
           r"PROGRAM_CACHE_STORE|NEGATIVE_CACHE_HIT|NEGATIVE_CACHE_STORE|EXECUTION_DECLINE)$",
           r"^OPEN_EQUATION_PROGRAM", r"^OPEN_EQUATION_CURSOR", r"SPECIALIZER_.*CACHE", r"ACTIVATION_ADMISSION_CACHE",
           r"NAMED_ARITY_SOURCE_CACHE", r"PETTA_LIBPL_ADMISSION_NEGATIVE", r"PETTA_TYPE_OBLIGATION_CACHE",
           r"TYPECHECK_BOUNDARY_PLAN_CACHE", r"^PREPARED_PURE_PRECHECK", r"BINDINGS_APPLY", r"TERM_UNIVERSE_COPY",
           r"_ARENA_ALLOC_BYTES$", r"PETTA_PROGRAM_REVISION_VIEW_AUTHORITY", r"SPACE_.*REVISION|REVISION_.*SPACE"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("rundir")
    ap.add_argument("--json")
    ap.add_argument("--md")
    ap.add_argument("--grep", action="append")
    a = ap.parse_args()
    pats = [re.compile(p) for p in (a.grep or DEFAULT)]
    data = {}
    for w in WORKLOADS:
        runs = collections.defaultdict(collections.Counter)
        for path in sorted(glob.glob(os.path.join(a.rundir, w, "*.stats.r*.stderr"))):
            r = re.search(r"\.r(\d+)\.stderr$", path).group(1)
            for ln in open(path, errors="replace"):
                m = LINE.match(ln.strip())
                if m:
                    runs[r][m.group(1)] += int(m.group(2))
        data[w] = runs
    out = {"workloads": {}}
    lines = ["# cetta-internals P: CeTTa runtime counters (generated by bench/p/stats_report.py)", "",
             "Summed over each workload's files; run 1 shown; '*' marks a counter that differs between runs.", "",
             "| counter | " + " | ".join(WORKLOADS) + " |", "|---|" + "---|" * len(WORKLOADS)]
    names = set()
    for w, runs in data.items():
        if not runs:
            continue
        first = runs[sorted(runs)[0]]
        varying = {k for k in first if any(runs[r].get(k) != first.get(k) for r in runs)}
        out["workloads"][w] = {"runs": sorted(runs), "counters": {k: v for k, v in first.items() if v},
                               "varying": sorted(varying)}
        names |= {k for k, v in first.items() if v and any(p.search(k.upper().replace("-", "_")) for p in pats)}
    for k in sorted(names):
        cells = []
        for w in WORKLOADS:
            o = out["workloads"].get(w)
            v = o["counters"].get(k, 0) if o else None
            cells.append("" if v is None else ("{:,}".format(v) + ("*" if o and k in o["varying"] else "")))
        lines.append("| %s | %s |" % (k, " | ".join(cells)))
    text = "\n".join(lines) + "\n"
    if a.md:
        open(a.md, "w").write(text)
    else:
        print(text)
    if a.json:
        json.dump(out, open(a.json, "w"), indent=1, sort_keys=True)


if __name__ == "__main__":
    main()
