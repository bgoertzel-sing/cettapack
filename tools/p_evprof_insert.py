#!/usr/bin/env python3
"""cetta-internals P: add the evaluator's phase timers (upstream/cetta-p/0011) to a CeTTa source tree.

  p_evprof_insert.py SRC_TREE SITES_TXT

For every function named in SITES_TXT (lines "PHASE FUNCTION"), every definition of it in SRC_TREE/src (*.c, *.inc,
binding/*.c) gets, as the first statement of its body, CETTA_EVPROF_SCOPE(<site>); the file gets
#include "cetta_evprof.h".  A definition is a line starting at column 0 with an identifier, containing
"FUNCTION(", whose signature (up to the first "{" or ";") ends with "{": prototypes are skipped.  Writes
src/cetta_evprof_sites.def (the X-macro table, in SITES_TXT order).  Fails if a function has no definition.
With CETTA_EVPROF=0 the macro expands to nothing, so the off build compiles the same code as without the patch.
"""
import os
import re
import sys

root, sites_path = sys.argv[1], sys.argv[2]
sites = []
for ln in open(sites_path):
    ln = ln.split("#", 1)[0].strip()
    if ln:
        phase, fn = ln.split()
        sites.append((phase, fn))
names = {fn for _, fn in sites}
src = os.path.join(root, "src")
files = []
for d, _, fs in os.walk(src):
    if "generated" in d:
        continue
    for f in fs:
        if f.endswith((".c", ".inc")) and not f.startswith("cetta_evprof"):
            files.append(os.path.join(d, f))
files.sort()
found = {fn: 0 for fn in names}
ident = re.compile(r"\b([A-Za-z_][A-Za-z0-9_]*)\(")
for path in files:
    lines = open(path).read().split("\n")
    out, changed, i = [], False, 0
    while i < len(lines):
        ln = lines[i]
        hit = None
        if ln and (ln[0].isalpha() or ln[0] == "_") and not ln.startswith(("return", "if", "else", "typedef")):
            for m in ident.finditer(ln):
                if m.group(1) in names:
                    # the name must be the declarator: only type words / '*' before it
                    before = re.sub(r"__attribute__\(\((?:[^()]|\([^()]*\))*\)\)", "", ln[:m.start()])
                    if re.fullmatch(r"[A-Za-z0-9_ \*]*", before):
                        hit = m.group(1)
                    break
        if hit:
            # scan the signature
            j, sig = i, ""
            while j < len(lines):
                sig += lines[j] + "\n"
                s = sig
                if "{" in s or ";" in s:
                    break
                j += 1
            brace, semi = sig.find("{"), sig.find(";")
            if brace >= 0 and (semi < 0 or brace < semi) and sig.rstrip().endswith("{"):
                out.extend(lines[i:j + 1])
                out.append("    CETTA_EVPROF_SCOPE(CETTA_EVP_%s);" % hit)
                found[hit] += 1
                changed = True
                i = j + 1
                continue
        out.append(ln)
        i += 1
    if changed:
        text = "\n".join(out)
        # include after the first block of #include lines
        m = re.search(r"^#include [^\n]*\n", text, re.M)
        inc = '#include "cetta_evprof.h"\n'
        text = text[:m.start()] + inc + text[m.start():] if m else inc + text
        open(path, "w").write(text)
        print("%s: %d" % (os.path.relpath(path, root), sum(1 for x in out if "CETTA_EVPROF_SCOPE(" in x)))
missing = [fn for fn, n in found.items() if n == 0]
if missing:
    sys.exit("no definition found for: " + " ".join(sorted(missing)))
with open(os.path.join(src, "cetta_evprof_sites.def"), "w") as f:
    f.write("/* generated by cettapack tools/p_evprof_insert.py from bench/p/evprof_sites.txt: EVP(site, phase) */\n")
    for phase, fn in sites:
        f.write('EVP(%s, "%s")\n' % (fn, phase))
dups = {fn: n for fn, n in found.items() if n > 1}
print("sites:", len(sites), "definitions instrumented:", sum(found.values()), "multiple definitions:", dups)
