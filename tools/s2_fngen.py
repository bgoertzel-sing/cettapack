#!/usr/bin/env python3
"""S2: extract the verbatim definitions (type declarations and equations, in file order) of the functions
cettapack S2 compiles, and of every callee/helper their compiled code relies on, from PeTTaChainer b0e24f9b's
pettachainer/metta/*.metta; write them as C strings (src/cpk_s2_fns_text.h).

  s2_fngen.py CHAINER_METTA_DIR OUT.h
"""
import glob, hashlib, os, sys

FUNCTIONS = [
    # compiled functions and the helpers whose equations their code reproduces
    "make-and-bundle",
    "and-bundle-premises",
    "frontier-remaining-score",
    "frontier-pool-potential",
    "expr-arity",
    "premises-expected-confidence",
    "premises-expected-confidence-step",
    "term-confidence",
    "proof-score",
    "tv-confidence",
    "proof-output-key-by-id",
    "proof-output-atom-by-id",
    "proof-output-atom",
    "candidate-output-key",
]
# constructors the compiled code builds or dispatches on: they must have no equations (checked at run time);
# their declarations are part of the guarded text when present
CONSTRUCTORS = ["and-bundle", "proof-output-key", "STV", "CTV", "CPU", "pool-part", "marginal-proj",
                "stored-proof-row"]


def forms(text):
    """top-level forms: (start, end) of each balanced s-expression outside comments/strings"""
    i, n, depth, start, out = 0, len(text), 0, None, []
    while i < n:
        c = text[i]
        if c == ';':
            while i < n and text[i] != '\n':
                i += 1
            continue
        if c == '"':
            i += 1
            while i < n and text[i] != '"':
                i += 2 if text[i] == '\\' else 1
            i += 1
            continue
        if c == '(':
            if depth == 0:
                start = i
            depth += 1
        elif c == ')':
            depth -= 1
            if depth == 0:
                bang = start > 0 and text[start - 1] == '!'
                out.append((text[start:i + 1], bang))
        i += 1
    return out


def head_of(form):
    toks = form[1:].replace('(', ' ( ').replace(')', ' ) ').split()
    if len(toks) < 3:
        return None, None
    if toks[0] == '=' and toks[1] == '(':
        return '=', toks[2]
    if toks[0] == ':':
        return ':', toks[1]
    return None, None


def strip_comments(form):
    lines = []
    for ln in form.split('\n'):
        # drop ; comments outside strings (the definitions here have no strings holding ';')
        if ';' in ln and '"' not in ln:
            ln = ln[:ln.index(';')]
        lines.append(ln.rstrip())
    return '\n'.join(l for l in lines if l.strip())


def main():
    src, out = sys.argv[1], sys.argv[2]
    defs = {f: [] for f in FUNCTIONS + CONSTRUCTORS}
    files = sorted(glob.glob(os.path.join(src, '*.metta')))
    digest = hashlib.sha256()
    for f in files:
        text = open(f).read()
        for form, bang in forms(text):
            if bang:
                continue
            kind, name = head_of(form)
            if name in defs:
                defs[name].append((kind, os.path.basename(f), strip_comments(form)))
                digest.update(form.encode())
    L = ["/* generated by tools/s2_fngen.py from PeTTaChainer b0e24f9b pettachainer/metta: verbatim type declarations",
         " * and equations (comments stripped), in file order.  sha256 of the extracted forms: %s */" % digest.hexdigest(),
         "#ifndef CPK_S2_FNS_TEXT_H", "#define CPK_S2_FNS_TEXT_H", ""]
    for name in FUNCTIONS + CONSTRUCTORS:
        cname = "S2_DEF_" + name.upper().replace('-', '_').replace('?', 'P').replace('!', 'B')
        eqs = [d for d in defs[name] if d[0] == '=']
        decls = [d for d in defs[name] if d[0] == ':']
        if name in FUNCTIONS and not eqs:
            sys.exit("no equation for %s" % name)
        if len(decls) > 1:
            sys.exit("more than one declaration for %s" % name)
        L.append("/* %s: %s */" % (name, ", ".join("%s %s" % (k, f) for k, f, _ in defs[name])))
        L.append("static const char *const %s_EQS[] = {" % cname)
        for _, _, t in eqs:
            L.append("    " + c_str(t) + ",")
        L.append("    NULL};")
        L.append("static const char *const %s_DECL = %s;" % (cname, c_str(decls[0][2]) if decls else "NULL"))
        L.append("")
    L.append("#endif")
    open(out, "w").write("\n".join(L) + "\n")


def c_str(t):
    return '"' + t.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n"\n    "') + '"'


main()
