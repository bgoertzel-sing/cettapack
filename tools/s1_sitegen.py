#!/usr/bin/env python3
"""S1: extract the equations the compiled S1 sites are compiled from, verbatim, from PeTTaChainer b0e24f9b
(git show REV:pettachainer/metta/FILE), and write them as C string constants (src/cpk_s1_sites_text.h).

  tools/s1_sitegen.py CHAINER_REPO > src/cpk_s1_sites_text.h

Each site names the file and the head; the equation is the balanced s-expression starting at the line
'(= (HEAD' (comments stripped).  The header records the source file, line and sha256 of the text.
"""
import hashlib
import subprocess
import sys

REV = "b0e24f9b9d7106ccabf51917f1703abf3ab8c570"
SITES = [
    # (C name, file, head)
    ("S1_EQ_FORWARD_REGISTER_BASE_RATE", "forward_chainer.metta", "forward-register-base-rate!"),
]


def strip_comment(line):
    out, in_str = [], False
    for ch in line:
        if ch == '"':
            in_str = not in_str
        if ch == ';' and not in_str:
            break
        out.append(ch)
    return "".join(out)


def extract(text, head):
    lines = text.split("\n")
    for i, ln in enumerate(lines):
        if ln.startswith("(= (%s" % head) and (len(ln) == len("(= (%s" % head) or ln[len("(= (%s" % head)] in " \t)"):
            buf, depth, started = [], 0, False
            for j in range(i, len(lines)):
                s = strip_comment(lines[j])
                buf.append(s.rstrip())
                for ch in s:
                    if ch == "(":
                        depth += 1
                        started = True
                    elif ch == ")":
                        depth -= 1
                if started and depth == 0:
                    return i + 1, "\n".join(buf).strip()
    raise SystemExit("equation of %s not found" % head)


def main():
    repo = sys.argv[1]
    print("/* generated by tools/s1_sitegen.py from PeTTaChainer %s; do not edit */" % REV)
    print("#ifndef CPK_S1_SITES_TEXT_H\n#define CPK_S1_SITES_TEXT_H")
    for cname, f, head in SITES:
        text = subprocess.run(["git", "-C", repo, "show", "%s:pettachainer/metta/%s" % (REV, f)],
                              capture_output=True, text=True, check=True).stdout
        line, eq = extract(text, head)
        sha = hashlib.sha256(eq.encode()).hexdigest()
        print("/* %s:%d, %d chars, sha256 %s */" % (f, line, len(eq), sha))
        print("static const char %s[] =" % cname)
        for ln in eq.split("\n"):
            print('    "%s\\n"' % ln.replace("\\", "\\\\").replace('"', '\\"'))
        print("    ;")
    print("#endif")


if __name__ == "__main__":
    main()
