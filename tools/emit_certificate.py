#!/usr/bin/env python3
"""Emit the per-pack certificate skeleton in the A.8 shape.

  tools/emit_certificate.py PACK_DIR TEST_LOG KB [HE_LOG]

Writes PACK_DIR/certificate.metta only when every test item passed. Claim
level bag-tested-adequate (A.8): on every tested input the kernel's answer bag
equaled generic CeTTa's, multiplicities included, and every guard failure fell
back to a bag equal to generic CeTTa's. Steps are recorded with the evidence
that stands behind each; none is proved.
"""
import hashlib
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def sha(path):
    with open(path, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()


def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(pack_dir, test_log, kb_path, he_log=None):
    manifest_path = os.path.join(pack_dir, "manifest.json")
    m = json.load(open(manifest_path))
    results = [json.loads(l) for l in open(test_log) if l.strip()]
    failed = [r for r in results if not r["ok"]]
    he_line = open(he_log).read().strip() if he_log and os.path.exists(he_log) else "not run"
    if failed or he_line.startswith("FAIL"):
        print(f"refusing to certify: {len(failed)} failed item(s); HE: {he_line}", file=sys.stderr)
        return 1
    idn, sp, x = m["identity"], m["spaces"][0], m["x_cettapack"]
    head = subprocess.check_output(["git", "-C", ROOT, "rev-parse", "HEAD"], text=True).strip()
    items = " ".join(r["item"] for r in results)
    vector = (f"((space-id {q(sp['space_id'])}) (schema-hash {q(sp['schema_hash'])}) "
              f"(revision-policy {sp['revision_policy']}) (multiplicity-source {sp['multiplicity_source']}) "
              f"(revision-or-epoch instantiation))")
    text = f"""; CettaPack certificate skeleton (A.8). Generated by tools/emit_certificate.py.
; Nothing here is proved: each step names the evidence behind it.
(supercompile-cert
  :manifest-version {m['manifest_version']}
  :source-span-hash {q(idn['source_span_hash'])}
  :normalized-region-hash {q(idn['normalized_region_hash'])}
  :meta-expanded-region-hash {q(idn['meta_expanded_region_hash'])}
  :match-pattern-hash {q(idn['match_pattern_hash'])}
  :profile-digest {q(idn['profile_digest'])}
  :langdef-pack-digest {q(idn['langdef_pack_digest'])}
  :effect-summary ({' '.join(q(e) for e in m['effects']['classes'])} (isolation {m['effects']['isolation']}))
  :space-dependency-vector ({vector})
  :backend-schema {x['kernel']['backend_schema']}
  :exactness {idn['exactness_signature']}
  :claim-level bag-tested-adequate
  :steps
    ((parse-and-normalize step-id-1 (evidence "CeTTa parse; cpk-normalized-v1 hash equal in tools/cpkc.py and the C loader"))
     (meta-expand step-id-2 (evidence "identity: the region holds no macros or meta-rules"))
     (choose-pathmap-prefix step-id-3 (evidence {q('join order ' + str(x['kernel']['join_order']) + '; key (atom group-id); prefix = constants and bound fields up to the first unbound one')}))
     (prove-or-claim-candidate-soundness step-id-4 (claim "every record that can match a factor reaches its key prefix: schema guard admits only flat all-symbol records of the compiled relations") (evidence "tested, not proved"))
     (native-seeded-rematch-parity step-id-5 (evidence "space_match_backend_match_atom_seeded on every candidate"))
     (result-template-instantiation step-id-6 (evidence "bindings_apply on the parsed template; A.9 item 7"))
     (multiplicity-reconstruction step-id-7 (evidence "record counts per candidate, product over the join after rematch; A.9 items 4 and 15"))
     (residualize-to-c-kernel step-id-8 (evidence {q(x['kernel']['plan_file'] + ' sha256 ' + m['artifacts']['native_plan_hash'])})))
  :evidence
    ((tests {q(items)})
     (test-log-sha256 {q(sha(test_log))})
     (he-comparison {q(he_line)})
     (kb-sha256 {q(sha(kb_path) if os.path.exists(kb_path) else 'missing')})
     (kb-generator "bench/gen_kb.py --seed 20261106")
     (manifest-sha256 {q(sha(manifest_path))})
     (cettapack-commit {q(head)})
     (cetta-commit {q(x['profile_components']['cetta'])}))
  :open-obligations
    ("rule-sound-on-fragment: VALID guard implies kernel bag = generic bag for all spaces of the fragment (unproved)"
     "candidate soundness and completeness of the PathMap prefix (step-id-4)"
     "rematch exactness is CeTTa's own; not re-verified"
     "Lean: not part of M1 (A.10)"))
"""
    out = os.path.join(pack_dir, "certificate.metta")
    with open(out, "w") as fh:
        fh.write(text)
    print(f"wrote {os.path.relpath(out, ROOT)}: {len(results)} items + HE, claim bag-tested-adequate")
    return 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:5]))
